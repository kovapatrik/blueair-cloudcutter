"""Generate (and optionally start) the supporting network services.

The device needs three things from us:

* an AP called `BAFactory` (only for the UART / wiped-NVS route),
* DNS that resolves `factoryserver.blueair` to this machine,
* a broker with a certificate chaining to the CA we planted in `db.c-r`.

Config files are generated rather than checked in, so paths and IPs are always
correct for the current run.
"""

from __future__ import annotations

import shutil
import socket
import subprocess
import sys
import threading
import time
from pathlib import Path

from .constants import FACTORY_HOST, FACTORY_PSK, FACTORY_SSID
from .errors import CutterError
from .util import info, which


def hostapd_conf(
    iface: str,
    *,
    ssid: str = FACTORY_SSID,
    psk: str = FACTORY_PSK,
    channel: int = 6,
    country: str | None = None,
) -> str:
    country_line = f"country_code={country}\n" if country else ""
    return f"""# generated by blueair-cloudcutter
{country_line}interface={iface}
driver=nl80211
ssid={ssid}
hw_mode=g
channel={channel}
wmm_enabled=1
auth_algs=1
wpa=2
wpa_key_mgmt=WPA-PSK
wpa_pairwise=CCMP
rsn_pairwise=CCMP
wpa_passphrase={psk}
ignore_broadcast_ssid=0
"""


def dnsmasq_conf(
    iface: str,
    *,
    gateway: str,
    upstream: str = "1.1.1.1",
    dns_port: int = 53,
    dhcp_dns: str | None = None,
) -> str:
    network = ".".join(gateway.split(".")[:3])
    if dns_port == 0:
        port_line = "port=0\n"
    elif dns_port != 53:
        port_line = f"port={dns_port}\n"
    else:
        port_line = ""
    resolver = dhcp_dns or gateway
    return f"""# generated by blueair-cloudcutter
{port_line}interface={iface}
bind-interfaces
dhcp-range={network}.10,{network}.100,255.255.255.0,12h
dhcp-option=3,{gateway}
dhcp-option=6,{resolver}
address=/{FACTORY_HOST}/{gateway}
server={upstream}
log-queries
log-dhcp
"""


def mosquitto_conf(
    *,
    port: int = 8883,
    ca: Path,
    cert: Path,
    key: Path,
    bind: str = "0.0.0.0",
    require_certificate: bool = False,
) -> str:
    return f"""# generated by blueair-cloudcutter
listener {port} {bind}
allow_anonymous true
require_certificate {"true" if require_certificate else "false"}
cafile {ca}
certfile {cert}
keyfile {key}
tls_version tlsv1.2
"""


def write_configs(outdir: Path, **kwargs) -> dict[str, Path]:
    outdir.mkdir(parents=True, exist_ok=True)
    files: dict[str, Path] = {}
    files["hostapd"] = outdir / "hostapd.conf"
    files["hostapd"].write_text(
        hostapd_conf(
            kwargs.get("iface", "wlan0"),
            ssid=kwargs.get("ssid", FACTORY_SSID),
            psk=kwargs.get("psk", FACTORY_PSK),
            channel=kwargs.get("channel", 6),
            country=kwargs.get("country"),
        )
    )

    files["dnsmasq"] = outdir / "dnsmasq.conf"
    files["dnsmasq"].write_text(
        dnsmasq_conf(
            kwargs.get("iface", "wlan0"),
            gateway=kwargs.get("gateway", "192.168.50.1"),
            dns_port=kwargs.get("dns_port", 53),
            dhcp_dns=kwargs.get("dhcp_dns"),
        )
    )

    if kwargs.get("ca") and kwargs.get("cert"):
        files["mosquitto"] = outdir / "mosquitto.conf"
        files["mosquitto"].write_text(
            mosquitto_conf(
                port=kwargs.get("port", 8883),
                ca=Path(kwargs["ca"]),
                cert=Path(kwargs["cert"]),
                key=Path(kwargs["key"]),
                bind=kwargs.get("bind", "0.0.0.0"),
            )
        )
    return files


def write_mqtt_bundle(
    materials,
    outdir: Path,
    *,
    port: int = 8883,
    sans: list[str] | None = None,
) -> Path:
    """Write a self-contained mosquitto folder that can be scp'd elsewhere.

    The config uses paths relative to this directory and ``start.sh`` changes
    into it first, so the same folder works on the Pi and on another machine.
    """
    materials.ensure_broker(sorted(set(sans or ["localhost"])))
    outdir.mkdir(parents=True, exist_ok=True)

    files = {
        "ca.pem": materials.ca_cert,
        "broker.pem": materials.broker_cert,
        "broker-chain.pem": materials.p("broker-chain.pem"),
        "broker.key": materials.broker_key,
    }
    for name, source in files.items():
        if source.exists():
            shutil.copy2(source, outdir / name)
    (outdir / "broker.key").chmod(0o600)

    conf = outdir / "mosquitto.conf"
    conf.write_text(
        mosquitto_conf(
            port=port,
            ca=Path("ca.pem"),
            cert=Path("broker-chain.pem"),
            key=Path("broker.key"),
        )
    )
    start = outdir / "start.sh"
    start.write_text('#!/bin/sh\ncd "$(dirname "$0")"\nexec mosquitto -c mosquitto.conf -v "$@"\n')
    start.chmod(0o755)
    (outdir / "README.txt").write_text(
        "BlueAir CloudCutter local MQTT broker\n"
        "\n"
        "Run it from this directory:\n"
        "  ./start.sh\n"
        "or:\n"
        "  mosquitto -c mosquitto.conf -v\n"
        "\n"
        "The device dials this broker using the SAN in broker-chain.pem.\n"
        "Keep broker.key private.\n"
    )
    return conf


class Process:
    """A background process with a readable log file."""

    def __init__(self, cmd: list[str], log: Path, cwd: Path | None = None, *, echo: bool = False) -> None:
        self.cmd = cmd
        self.log = log
        self.cwd = cwd
        self.echo = echo
        self.proc: subprocess.Popen | None = None
        self._fh = None
        self._reader: threading.Thread | None = None

    def start(self) -> Process:
        exe = which(self.cmd[0])
        if not exe:
            raise CutterError(f"{self.cmd[0]} is not installed")
        self.log.parent.mkdir(parents=True, exist_ok=True)
        self._fh = self.log.open("ab")
        info(" ".join(self.cmd))
        if self.echo:
            # Tee instead of redirecting, so a foreground server shows its log.
            self.proc = subprocess.Popen(
                self.cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                cwd=str(self.cwd) if self.cwd is not None else None,
                text=True,
                errors="replace",
                bufsize=1,
            )
            self._reader = threading.Thread(target=self._forward, daemon=True)
            self._reader.start()
        else:
            self.proc = subprocess.Popen(
                self.cmd,
                stdout=self._fh,
                stderr=subprocess.STDOUT,
                cwd=str(self.cwd) if self.cwd is not None else None,
            )
        return self

    def _forward(self) -> None:
        assert self.proc is not None and self.proc.stdout is not None
        for line in self.proc.stdout:
            self._fh.write(line.encode("utf-8", "replace"))
            self._fh.flush()
            sys.stdout.write(line)
            sys.stdout.flush()

    def stop(self) -> None:
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.proc.kill()
                self.proc.wait()
        if self._reader is not None:
            self._reader.join(timeout=2)
            if self._reader.is_alive():
                return
        try:
            self._fh.close()
        except Exception:
            pass

    def __enter__(self) -> Process:
        return self.start()

    def __exit__(self, *exc) -> None:
        self.stop()


def start_mosquitto(conf: Path, log: Path, *, echo: bool = False) -> Process:
    # Started as an unprivileged user (see the wrapper), so mosquitto does not
    # drop privileges and can read the 0600 broker.key it owns.
    return Process(["mosquitto", "-c", conf.name, "-v"], log, cwd=conf.parent, echo=echo)


# -- host addressing and NAT -------------------------------------------------


def _run(argv: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(argv, text=True, capture_output=True)


def parse_default_iface(text: str) -> str | None:
    for line in text.splitlines():
        parts = line.split()
        if line.startswith("default") and "dev" in parts:
            return parts[parts.index("dev") + 1]
    return None


def default_route_iface() -> str | None:
    return parse_default_iface(_run(["ip", "route", "show", "default"]).stdout)


def parse_default_gateway(text: str) -> str | None:
    for line in text.splitlines():
        parts = line.split()
        if line.startswith("default") and "via" in parts:
            return parts[parts.index("via") + 1]
    return None


def default_gateway() -> str | None:
    """The uplink router, which is also the network's usual DNS server."""
    return parse_default_gateway(_run(["ip", "route", "show", "default"]).stdout)


def ipv4_addresses(iface: str) -> set[str]:
    result = _run(["ip", "-4", "-o", "addr", "show", "dev", iface])
    addresses: set[str] = set()
    for line in result.stdout.splitlines():
        parts = line.split()
        if "inet" in parts:
            addresses.add(parts[parts.index("inet") + 1].split("/")[0])
    return addresses


def _stop_clients(iface: str) -> None:
    """Stop a supplicant/DHCP client left on the AP interface.

    Only useful when the container shares the host PID namespace (`--pid=host`).
    """
    if not which("pgrep"):
        return
    from .util import warn

    for pattern in (f"wpa_supplicant.*{iface}", f"dhclient.*{iface}"):
        pids = _run(["pgrep", "-f", pattern]).stdout.split()
        for pid in pids:
            _run(["kill", pid])
        deadline = time.time() + 5
        for pid in pids:
            while time.time() < deadline:
                try:
                    state = Path(f"/proc/{pid}/stat").read_text().split()[2]
                except (OSError, IndexError):
                    break
                if state == "Z":
                    break
                time.sleep(0.1)
            else:
                warn(f"{pattern} (pid {pid}) did not exit")


def prepare_interface(iface: str) -> None:
    """Free the adapter and switch it to AP mode, like cloudcutter's setup_apmode.sh.

    brcmfmac (the Pi's driver) can reset the interface after a supplicant exits,
    so take it down and set the type explicitly before hostapd starts.
    """
    _stop_clients(iface)
    _run(["rfkill", "unblock", "wifi"])
    _run(["iw", "dev", iface, "disconnect"])
    _run(["ip", "link", "set", "dev", iface, "down"])
    result = _run(["iw", "dev", iface, "set", "type", "__ap"])
    if result.returncode != 0:
        from .util import warn

        warn(
            f"could not set {iface} to AP mode ({result.stderr.strip() or 'iw failed'}); "
            "hostapd will try anyway"
        )
    _run(["ip", "addr", "flush", "dev", iface])


def ensure_address(iface: str, address: str, prefix: int = 24) -> bool:
    """Give the AP interface its gateway address. Returns True if it was added."""
    if address in ipv4_addresses(iface):
        _run(["ip", "link", "set", "up", "dev", iface])
        return False
    result = _run(["ip", "addr", "add", f"{address}/{prefix}", "dev", iface])
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        raise CutterError(f"could not assign {address}/{prefix} to {iface}: {detail}")
    _run(["ip", "link", "set", "up", "dev", iface])
    return True


def remove_address(iface: str, address: str, prefix: int = 24) -> None:
    _run(["ip", "addr", "del", f"{address}/{prefix}", "dev", iface])


class Nat:
    """Route the AP subnet to the uplink, and undo exactly what was added."""

    def __init__(self, ap_iface: str, upstream: str) -> None:
        self.ap_iface = ap_iface
        self.upstream = upstream
        self.added: list[list[str]] = []
        self._forward: str | None = None

    @property
    def forward_before(self) -> str | None:
        return self._forward

    def _rules(self) -> list[tuple[list[str], list[str]]]:
        ap, up = self.ap_iface, self.upstream
        return [
            (
                ["iptables", "-t", "nat", "-C", "POSTROUTING", "-o", up, "-j", "MASQUERADE"],
                ["iptables", "-t", "nat", "-A", "POSTROUTING", "-o", up, "-j", "MASQUERADE"],
            ),
            (
                ["iptables", "-C", "FORWARD", "-i", ap, "-o", up, "-j", "ACCEPT"],
                ["iptables", "-A", "FORWARD", "-i", ap, "-o", up, "-j", "ACCEPT"],
            ),
            (
                [
                    "iptables",
                    "-C",
                    "FORWARD",
                    "-i",
                    up,
                    "-o",
                    ap,
                    "-m",
                    "state",
                    "--state",
                    "RELATED,ESTABLISHED",
                    "-j",
                    "ACCEPT",
                ],
                [
                    "iptables",
                    "-A",
                    "FORWARD",
                    "-i",
                    up,
                    "-o",
                    ap,
                    "-m",
                    "state",
                    "--state",
                    "RELATED,ESTABLISHED",
                    "-j",
                    "ACCEPT",
                ],
            ),
        ]

    def start(self) -> None:
        iptables = which("iptables")
        if not iptables:
            raise CutterError(
                "iptables is not installed; use `helpers serve network` if your router already routes"
            )
        self._rules_argv = [_rewrite(rule, iptables) for rule in self._rules()]

        forward = Path("/proc/sys/net/ipv4/ip_forward")
        try:
            self._forward = forward.read_text().strip()
            if self._forward != "1":
                forward.write_text("1\n")
        except OSError as exc:
            raise CutterError(f"could not enable IP forwarding: {exc}") from exc

        for check, add in self._rules_argv:
            if _run(check).returncode == 0:
                continue
            result = _run(add)
            if result.returncode != 0:
                self.stop()
                raise CutterError(
                    f"NAT setup failed: {result.stderr.strip() or result.stdout.strip()}\n"
                    "Fix the firewall, or use `helpers serve network` if your router already routes."
                )
            self.added.append(add)

    def stop(self) -> None:
        for add in reversed(self.added):
            delete = ["-D" if arg == "-A" else arg for arg in add]
            _run(delete)
        self.added.clear()
        if self._forward is not None and self._forward != "1":
            try:
                Path("/proc/sys/net/ipv4/ip_forward").write_text(self._forward + "\n")
            except OSError:
                pass


def _rewrite(argv: list[str], iptables: str) -> list[str]:
    out = list(argv)
    out[0] = iptables
    return out


def port_free(port: int, proto: str = "udp") -> bool:
    kind = socket.SOCK_DGRAM if proto == "udp" else socket.SOCK_STREAM
    sock = socket.socket(socket.AF_INET, kind)
    try:
        sock.bind(("0.0.0.0", port))
        return True
    except OSError:
        return False
    finally:
        sock.close()


def pick_dns_port() -> int:
    """53 is usually taken by AdGuard/pi-hole/systemd-resolved on a homelab host."""
    for port in (53, 5353, 5354):
        if port_free(port, "udp") and port_free(port, "tcp"):
            return port
    raise CutterError("no free DNS port (tried 53, 5353, 5354)")


def add_dns_redirect(iface: str, to_port: int) -> list[list[str]]:
    """Send the AP clients' :53 queries to dnsmasq's alternate port."""
    if to_port in (0, 53) or not which("iptables"):
        return []
    added: list[list[str]] = []
    for proto in ("udp", "tcp"):
        check = [
            "iptables",
            "-t",
            "nat",
            "-C",
            "PREROUTING",
            "-i",
            iface,
            "-p",
            proto,
            "--dport",
            "53",
            "-j",
            "REDIRECT",
            "--to-ports",
            str(to_port),
        ]
        add = [
            "iptables",
            "-t",
            "nat",
            "-A",
            "PREROUTING",
            "-i",
            iface,
            "-p",
            proto,
            "--dport",
            "53",
            "-j",
            "REDIRECT",
            "--to-ports",
            str(to_port),
        ]
        if _run(check).returncode == 0:
            continue
        result = _run(add)
        if result.returncode == 0:
            added.append(add)
        else:
            from .util import warn

            warn(f"could not redirect {proto}/53 to {to_port}: {result.stderr.strip()}")
    return added


def remove_rules(rules: list[list[str]]) -> None:
    for rule in reversed(rules):
        delete = ["-D" if arg == "-A" else arg for arg in rule]
        _run(delete)


def write_cleanup(path: Path, lines: list[str]) -> None:
    """Write an idempotent undo script, runnable inside the same netns."""
    body = "#!/bin/sh\n" + "\n".join([*lines, f"rm -f {path}"]) + "\n"
    path.write_text(body)
    path.chmod(0o755)
